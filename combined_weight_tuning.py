@dataclass(frozen=True)
class WeightConfig:
    config_id: str
    notes: str
    trend_w_bull_bull: float
    trend_w_bull_early: float
    trend_w_bull_neutral: float
    trend_w_neutral_bull: float
    trend_w_neutral_early: float
    trend_w_neutral_neutral: float
    trend_w_bull_bear: float
    trend_w_bear_any: float
    fair_value_missing_fill: float | None = None

    def trend_weight(self, industry_regime: str | None, subindustry_regime: str | None) -> float:
        industry = industry_regime if isinstance(industry_regime, str) else "Neutral"
        subindustry = subindustry_regime if isinstance(subindustry_regime, str) else "Neutral"
        industry = industry.strip()
        subindustry = subindustry.strip()
        if industry == "EarlyBull":
            industry = "Bull"

        if industry == "Bull" and subindustry == "Bull":
            return self.trend_w_bull_bull
        if industry == "Bull" and subindustry == "EarlyBull":
            return self.trend_w_bull_early
        if industry == "Bull" and subindustry == "Neutral":
            return self.trend_w_bull_neutral
        if industry == "Neutral" and subindustry == "Bull":
            return self.trend_w_neutral_bull
        if industry == "Neutral" and subindustry == "EarlyBull":
            return self.trend_w_neutral_early
        if industry == "Neutral" and subindustry == "Neutral":
            return self.trend_w_neutral_neutral
        if industry == "Bull" and subindustry == "Bear":
            return self.trend_w_bull_bear
        return self.trend_w_bear_any


