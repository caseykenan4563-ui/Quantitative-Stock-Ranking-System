"""
Walk-forward tuning for combined stock-ranking weights.

This script does not rebuild SEC fair-value scores. It consumes the
point-in-time score history generated by combined_score_backtest.py, then
re-ranks each historical anchor under different trend/fair-value/regime weight
matrices.

Workflow:
1. Load point-in-time score snapshots.
2. Load historical prices once for forward-return/risk evaluation.
3. Test candidate weight matrices.
4. Select weights on older folds and validate on the next fold.
5. Save return, drawdown, volatility, Sharpe/Sortino, capture, and tracking
   metrics for audit.
"""

