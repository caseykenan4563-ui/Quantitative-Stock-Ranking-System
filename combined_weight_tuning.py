def main() -> int:
    parser = argparse.ArgumentParser(description="Walk-forward tune combined-score weight matrices.")
    parser.add_argument("--score-history", type=Path, default=DEFAULT_SCORE_HISTORY)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--historical-price-file",
        type=Path,
        help=(
            "Optional canonical daily price CSV from historical_data_layer.py. "
            "Use this for Sharadar active/delisted prices instead of Yahoo."
        ),
    )
    parser.add_argument("--preset", choices=["compact", "expanded"], default="expanded")
    parser.add_argument("--top-n", type=int, default=100)
    parser.add_argument("--batch-size", type=int, default=25)
    parser.add_argument("--skip-risk-metrics", action="store_true")
    parser.add_argument("--save-holdings", action="store_true")
    parser.add_argument("--max-configs", type=int)
    args = parser.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)

    scores = prepare_score_history(args.score_history)
    configs = build_candidate_configs(args.preset)
    if args.max_configs is not None:
        configs = configs[:args.max_configs]
    if not configs:
        raise RuntimeError("No candidate configs selected")

    print(f"[INFO] Loaded {len(scores):,} point-in-time score rows", flush=True)
    print(f"[INFO] Testing {len(configs)} weight configs", flush=True)
    price_wide = fetch_price_wide(
        scores,
        args.batch_size,
        historical_price_file=args.historical_price_file,
    )
    print(f"[INFO] Price matrix: {len(price_wide):,} dates x {len(price_wide.columns):,} tickers", flush=True)

    all_results = []
    all_holdings = []
    for idx, config in enumerate(configs, start=1):
        print(f"[INFO] Evaluating config {idx}/{len(configs)}: {config.config_id}", flush=True)
        config_results, config_holdings = evaluate_config(
            scores=scores,
            config=config,
            price_wide=price_wide,
            top_n=args.top_n,
            include_risk_metrics=not args.skip_risk_metrics,
            save_holdings=args.save_holdings,
        )
        all_results.append(config_results)
        if args.save_holdings:
            all_holdings.append(config_holdings)

    results = pd.concat(all_results, ignore_index=True, sort=False) if all_results else pd.DataFrame()
    holdings = pd.concat(all_holdings, ignore_index=True, sort=False) if all_holdings else pd.DataFrame()
    horizon_summary = aggregate_results(results, ["Config_ID", "Horizon"])
    scorecard = score_configs(results)
    walk_forward, validation_results = walk_forward_selection(results)
    walk_forward_round_summary = aggregate_results(validation_results, ["Walk_Forward_Round"]) if not validation_results.empty else pd.DataFrame()
    walk_forward_overall = (
        score_configs(validation_results.assign(Config_ID="walk_forward_selected"))
        if not validation_results.empty else pd.DataFrame()
    )
    validation_scorecard = score_configs(validation_results) if not validation_results.empty else pd.DataFrame()

    metadata = {
        "status": "complete",
        "score_history": str(args.score_history),
        "historical_price_file": str(args.historical_price_file) if args.historical_price_file else None,
        "market_data_source": str(args.historical_price_file) if args.historical_price_file else "yfinance",
        "preset": args.preset,
        "top_n": args.top_n,
        "score_rows": int(len(scores)),
        "anchor_count": int(scores["Date"].nunique()),
        "candidate_config_count": int(len(configs)),
        "price_start_date": scores["Date"].min().strftime("%Y-%m-%d"),
        "price_end_date": price_wide.index.max().strftime("%Y-%m-%d"),
        "latest_price_date": price_wide.index.max().strftime("%Y-%m-%d"),
        "risk_metrics_included": not args.skip_risk_metrics,
        "top_holdings_saved": args.save_holdings,
        "objective_note": (
            "Risk_Adjusted_Objective = excess vs universe + 0.5 * excess vs XLK "
            "+ 0.010 * Sharpe + 0.005 * information ratio - downside/drawdown penalties."
        ),
    }

    args.output_dir.mkdir(parents=True, exist_ok=True)
    pd.DataFrame([asdict(config) for config in configs]).to_csv(args.output_dir / "candidate_configs.csv", index=False)
    results.to_csv(args.output_dir / "candidate_results.csv", index=False)
    if args.save_holdings:
        holdings.to_csv(args.output_dir / "candidate_top_holdings.csv", index=False)
    horizon_summary.to_csv(args.output_dir / "candidate_summary_by_horizon.csv", index=False)
    scorecard.to_csv(args.output_dir / "candidate_scorecard.csv", index=False)
    walk_forward.to_csv(args.output_dir / "walk_forward_selected_configs.csv", index=False)
    validation_results.to_csv(args.output_dir / "walk_forward_validation_results.csv", index=False)
    walk_forward_round_summary.to_csv(args.output_dir / "walk_forward_round_summary.csv", index=False)
    walk_forward_overall.to_csv(args.output_dir / "walk_forward_summary.csv", index=False)
    validation_scorecard.to_csv(args.output_dir / "walk_forward_validation_scorecard.csv", index=False)
    (args.output_dir / "run_metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    recommended = {
        "best_full_sample": scorecard.iloc[0].to_dict() if not scorecard.empty else {},
        "current_live": (
            scorecard[scorecard["Config_ID"] == "current_live"].iloc[0].to_dict()
            if not scorecard.empty and "current_live" in set(scorecard["Config_ID"])
            else {}
        ),
        "walk_forward_selected_config_counts": (
            walk_forward["Selected_Config_ID"].value_counts().to_dict()
            if not walk_forward.empty else {}
        ),
        "candidate_parameters": {
            config.config_id: asdict(config)
            for config in configs
        },
        "recommendation_note": (
            "Do not automatically patch production weights from the full-sample winner. "
            "Use walk-forward validation stability before changing comp.py."
        ),
    }
    (args.output_dir / "recommended_weights.json").write_text(
        json.dumps(recommended, indent=2, default=str),
        encoding="utf-8",
    )
    write_summary(
        output_dir=args.output_dir,
        scorecard=scorecard,
        horizon_summary=horizon_summary,
        walk_forward=walk_forward,
        walk_forward_overall=walk_forward_overall,
        configs=configs,
        metadata=metadata,
    )

    print("\n=== WEIGHT TUNING SCORECARD ===", flush=True)
    cols = [
        "Config_ID",
        "Risk_Adjusted_Objective",
        "Return_Objective",
        "Top_Excess_vs_Universe",
        "Top_Excess_vs_XLK",
        "Avg_Top_Sharpe",
        "Avg_Top_Max_Drawdown",
        "Avg_Top_Downside_Capture_vs_XLK",
    ]
    if not scorecard.empty:
        print(scorecard[[col for col in cols if col in scorecard.columns]].head(10).to_string(index=False), flush=True)

    print("\n=== WALK-FORWARD SELECTIONS ===", flush=True)
    if walk_forward.empty:
        print("[WARN] No walk-forward selections were produced.", flush=True)
    else:
        print(walk_forward.to_string(index=False), flush=True)

    print(f"\n[SUCCESS] Saved walk-forward tuning outputs to {args.output_dir}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
